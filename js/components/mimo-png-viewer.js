/**
 * Quizer T1 — view an already compiled Mimo PNG in an existing document job.
 *
 * This component only performs an authenticated artifact GET through the
 * caller-provided Quizer service. It cannot submit an extraction or start a
 * paid Mimo run. It deliberately does not bind figures to quiz questions:
 * that belongs to T2 after the canonical LaTeX/job contract.
 */
export function createMimoPngViewer({
  jobId, pageNumber, fetchImage, decodeImage, explainError,
  registerUrl = () => {},
} = {}) {
  if (typeof jobId !== "string" || !jobId ||
      !Number.isInteger(pageNumber) || pageNumber < 1 ||
      typeof fetchImage !== "function" || typeof decodeImage !== "function")
    throw new TypeError("Invalid compiled PNG viewer configuration");

  const element = (tag, text = "", className = "") => {
    const el = document.createElement(tag);
    if (className) el.className = className;
    el.textContent = text;
    return el;
  };
  const panel = element("section", "", "ai-generated-figure");
  panel.setAttribute("aria-label", "Compiled TikZ diagram for page " + pageNumber);
  const heading = element("h3", "Reconstructed diagram · page " + pageNumber);
  const note = element("p",
    "Generated by Mimo from the PDF. Compare its geometry with the original before importing.",
    "ai-muted");
  const retry = element("button", "View compiled PNG", "ai-secondary");
  retry.type = "button";
  const status = element("p", "Image stored in Mimo — not loaded yet.", "ai-muted");
  status.setAttribute("role", "status");
  status.setAttribute("aria-live", "polite");
  const visual = element("div", "", "ai-compiled-png");
  panel.append(heading, note, retry, status, visual);

  let loading = false;
  let loaded = false;

  async function load() {
    if (loading || loaded || !panel.isConnected) return false;
    loading = true;
    retry.disabled = true;
    status.textContent = "Retrieving compiled PNG from Mimo…";
    try {
      const response = await fetchImage(jobId, pageNumber);
      const png = decodeImage(response);
      // Discard a stale response if the user switched jobs or pages.
      if (!panel.isConnected) return false;
      const url = URL.createObjectURL(png);
      registerUrl(url);
      const img = element("img");
      img.src = url;
      img.alt = "TikZ-generated graph for PDF page " + pageNumber;
      img.loading = "eager";
      img.style.maxWidth = "min(100%,560px)";
      img.style.height = "auto";
      img.onerror = () => {
        if (!panel.isConnected) return;
        loaded = false;
        visual.replaceChildren();
        status.textContent = "The downloaded file could not be displayed as a PNG.";
        retry.textContent = "Retry PNG retrieval";
        retry.disabled = false;
      };
      const download = element("a", "Download compiled PNG", "ai-secondary");
      download.href = url;
      download.download = "page-" + pageNumber + "-tikz.png";
      if (typeof response?.sha256 === "string" &&
          /^[a-f0-9]{64}$/.test(response.sha256))
        download.title = "SHA-256: " + response.sha256;
      visual.replaceChildren(img, download);
      loaded = true;
      const size = Number.isSafeInteger(response?.byteLength) &&
        response.byteLength > 0 ? " · " +
        response.byteLength.toLocaleString() + " bytes" : "";
      status.textContent = "PNG ready" + size +
        ". Compare its geometry with the original PDF.";
      retry.textContent = "PNG loaded";
      return true;
    } catch (error) {
      if (panel.isConnected) {
        const message = typeof explainError === "function" ?
          explainError(error) : "Could not retrieve the compiled PNG.";
        status.textContent = message + " No new AI job was started.";
        retry.textContent = "Retry PNG retrieval";
      }
      return false;
    } finally {
      loading = false;
      if (panel.isConnected) retry.disabled = loaded;
    }
  }
  retry.addEventListener("click", () => { void load(); });
  return {panel, load};
}
