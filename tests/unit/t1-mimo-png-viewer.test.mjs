import test from "node:test";
import assert from "node:assert/strict";
import {createMimoPngViewer} from "../../js/components/mimo-png-viewer.js";

class Element {
  constructor(tag) {
    this.tagName=tag.toUpperCase();
    this.children=[];
    this.attributes={};
    this.events={};
    this.style={};
    this.textContent="";
    this.isConnected=false;
    this.disabled=false;
  }
  append(...children) {
    this.children.push(...children);
    if(this.isConnected)children.forEach(child=>{child.isConnected=true;});
  }
  replaceChildren(...children){
    this.children.forEach(child=>{child.isConnected=false;});
    this.children=[];
    this.append(...children);
  }
  setAttribute(name,value){this.attributes[name]=value;}
  addEventListener(name,cb){this.events[name]=cb;}
  click(){this.events.click?.();}
  query(tag) {
    if(this.tagName===tag.toUpperCase())return this;
    for(const child of this.children){const found=child.query(tag);if(found)return found;}
    return null;
  }
}

async function withDom(fn) {
  const oldDocument=globalThis.document,oldCreate=URL.createObjectURL;
  const urls=[];
  globalThis.document={createElement:tag=>new Element(tag)};
  URL.createObjectURL=blob=>{urls.push(blob);return "blob:quizer-test-"+urls.length;};
  try{await fn(urls);}finally{
    globalThis.document=oldDocument;
    URL.createObjectURL=oldCreate;
  }
}

const RUN_IMAGE={
  contentType:"image/png",
  base64:"iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAusB9Y9vlS8AAAAASUVORK5CYII=",
};
function fakePng() {return new Blob([Buffer.from(RUN_IMAGE.base64,"base64")],{type:"image/png"});}

test("T1: completed Mimo PNG is displayed and downloadable without starting any AI job",async()=>{
  await withDom(async blobs=>{
    const events=[],urls=[];
    const viewer=createMimoPngViewer({
      jobId:"owned-document",pageNumber:2,
      fetchImage:async(...args)=>{events.push(args);return RUN_IMAGE;},
      decodeImage:payload=>{
        assert.equal(payload,RUN_IMAGE);
        return fakePng();
      },
      registerUrl:url=>urls.push(url),
    });
    viewer.panel.isConnected=true;
    assert.equal(viewer.panel.query("a"),null);
    assert.equal(await viewer.load(),true);
    assert.deepEqual(events,[["owned-document",2]]);
    assert.equal(blobs.length,1);
    assert.equal(urls.length,1);
    assert.equal(viewer.panel.query("img").src,"blob:quizer-test-1");
    assert.equal(viewer.panel.query("a").download,"page-2-tikz.png");
    assert.equal(viewer.panel.query("a").href,"blob:quizer-test-1");
    assert.equal(viewer.panel.query("button").disabled,true);
    assert.equal(await viewer.load(),false,"download is cached within the viewer");
    assert.equal(events.length,1,"never submits another AI job");
  });
});

test("T1: backend failure has inline explanation and is retryable",async()=>{
  await withDom(async()=>{
    let calls=0;
    const viewer=createMimoPngViewer({
      jobId:"owned",pageNumber:2,fetchImage:async()=>{
        calls++;if(calls===1)throw Error("artifact missing");
        return RUN_IMAGE;
      },
      decodeImage:fakePng,
      explainError:()=>"Compiled image is unavailable.",
    });
    viewer.panel.isConnected=true;
    assert.equal(await viewer.load(),false);
    assert.match(viewer.panel.query("p").textContent,/Generated by Mimo/);
    const p=viewer.panel.children[3];
    assert.match(p.textContent,/Compiled image is unavailable/);
    assert.match(p.textContent,/No new AI job was started/);
    assert.equal(viewer.panel.query("button").disabled,false);
    assert.equal(await viewer.load(),true);
    assert.equal(calls,2);
  });
});

test("T1: detached page does not display stale image from another job",async()=>{
  await withDom(async blobs=>{
    let resolveResponse;
    const fetchImage=()=>new Promise(resolve=>{resolveResponse=resolve;});
    const viewer=createMimoPngViewer({
      jobId:"old-job",pageNumber:5,fetchImage,decodeImage:fakePng,
    });
    viewer.panel.isConnected=true;
    const loading=viewer.load();
    viewer.panel.isConnected=false;
    resolveResponse(RUN_IMAGE);
    assert.equal(await loading,false);
    assert.equal(blobs.length,0);
    assert.equal(viewer.panel.query("img"),null);
  });
});

test("T1: same viewer refuses duplicate concurrent fetches",async()=>{
  await withDom(async()=>{
    let calls=0, finish;
    const viewer=createMimoPngViewer({
      jobId:"owned",pageNumber:1,
      fetchImage:()=>{calls++;return new Promise(resolve=>{finish=resolve;});},
      decodeImage:fakePng,
    });
    viewer.panel.isConnected=true;
    const pending=viewer.load();
    assert.equal(viewer.panel.query("button").disabled,true);
    assert.equal(await viewer.load(),false);
    assert.equal(calls,1);
    finish(RUN_IMAGE);
    assert.equal(await pending,true);
  });
});

